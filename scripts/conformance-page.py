#!/usr/bin/env python3
"""Writes the check list of docs/conformance.md from the suite's registries.

Usage: scripts/conformance-page.py [--check | --write]

The list is generated, never written by hand, so it cannot drift from
the suite. It reads the two registries in lakelands-core, the doors'
suite (`conformance/checks/mod.rs`, `ALL`) and the engine seam's
(`conformance/engine/mod.rs`, `ENGINE_CHECKS`), and, for every entry,
the `check!` or `engine_check!` line that names it: the check's name and
the sentence that says where its rule is stated. Checks are grouped by
the file they live in, which is their subject, in registry order.

--check (the default, what CI runs) exits 1 when the page's generated
section differs from what the registries say; --write replaces it.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE = ROOT / "crates/lakelands-core/src/conformance"
PAGE = ROOT / "docs/conformance.md"
BEGIN = "<!-- The list below is generated by scripts/conformance-page.py from the registries; do not edit it by hand. -->"
END = "<!-- End of the generated list. -->"

RUST_STRING = r'"((?:[^"\\]|\\.)*)"'


def unescape(s):
    s = re.sub(r"\\\n\s*", "", s)
    return s.replace('\\"', '"').replace("\\\\", "\\")


def registry(mod_rs, array):
    """(file, constant) pairs in the order the registry lists them."""
    text = mod_rs.read_text("utf-8")
    m = re.search(r"pub const " + array + r": &\[[A-Za-z]+\] = &\[(.*?)\];", text, re.S)
    if not m:
        sys.exit(f"conformance-page: {mod_rs} has no `{array}` registry")
    return re.findall(r"([a-z0-9_]+)::([A-Z0-9_]+)", m.group(1))


def checks_in(rs, macro):
    """constant -> (name, about) for every check the file declares."""
    text = rs.read_text("utf-8")
    found = {}
    pattern = macro + r"!\(\s*(?:///[^\n]*\n\s*)*([A-Z0-9_]+)\s*=\s*(?:reopening\s+)?([a-z0-9_]+)\s*,\s*" + RUST_STRING
    for const, name, about in re.findall(pattern, text, re.S):
        found[const] = (name, unescape(about))
    return found


def section(title, entries, directory, macro):
    lines = [f"### {title} ({len(entries)} checks)", ""]
    groups = {}
    for file, const in entries:
        groups.setdefault(file, []).append(const)
    for file, consts in groups.items():
        declared = checks_in(directory / f"{file}.rs", macro)
        lines.append(f"**{file.replace('_', ' ')}**")
        lines.append("")
        for const in consts:
            if const not in declared:
                sys.exit(f"conformance-page: `{file}::{const}` is registered but no {macro}! declares it")
            name, about = declared[const]
            lines.append(f"- `{name}` — {about}")
        lines.append("")
    return lines


def generated():
    doors = registry(CORE / "checks/mod.rs", "ALL")
    engine = registry(CORE / "engine/mod.rs", "ENGINE_CHECKS")
    lines = [BEGIN, ""]
    lines += section("Through the doors", doors, CORE / "checks", "check")
    lines += section("Through the engine seam", engine, CORE / "engine", "engine_check")
    lines.append(END)
    return "\n".join(lines)


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    page = PAGE.read_text("utf-8")
    if BEGIN not in page or END not in page:
        sys.exit(f"conformance-page: {PAGE.relative_to(ROOT)} has no generated section")
    before, rest = page.split(BEGIN, 1)
    _, after = rest.split(END, 1)
    fresh = before + generated() + after
    if mode == "--write":
        PAGE.write_text(fresh, "utf-8")
        print(f"conformance-page: wrote {PAGE.relative_to(ROOT)}")
    elif mode == "--check":
        if fresh != page:
            sys.exit(
                f"conformance-page: {PAGE.relative_to(ROOT)} is stale; "
                "run scripts/conformance-page.py --write and commit the result"
            )
        print("conformance-page: the page lists every registered check")
    else:
        sys.exit("usage: scripts/conformance-page.py [--check | --write]")


if __name__ == "__main__":
    main()
