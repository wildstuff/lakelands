#!/usr/bin/env python3
"""Writes docs/refusals.md from the catalog, and holds the catalog to its rules.

Usage: scripts/refusals.py [--check [--shipped <page>] | --write]

The catalog is every `catalog!` and `named!` set in
`crates/lakelands-api/src/` (a `named!` set is plain names, each with
its sentence):
each case's code, its parameters by their names on the wire, its
sentence (the template) and what it is about. The page is generated,
never written by hand, so it cannot drift from the code.

--check (the default, what the `refusals` gate runs) exits 1 when the
page differs from what the catalog says, or when the catalog breaks a
rule of `docs/decisions/015-errors-are-a-closed-set-writes-answer-an-outcome.md`:

- **A sentence determines its case.** No two templates of a set can
  render the same text: each template is read as its words with every
  parameter standing for what its type can say (a number for digits,
  a list of names for names in backticks, foreign words for any text,
  anything else for text without a backtick, which no name holds), each
  optional segment read both as said and as not, and two that some text
  matches both are refused. A template names each of its parameters.
- **A code keeps its meaning.** Against the page at the last release
  tag, no code is removed or renamed, and no parameter is taken away or
  changes its type or whether it is optional; a case may gain optional
  parameters only, which a reader that does not know them ignores. With
  no page at that tag, nothing is compared.
- **A code leaves by a recorded withdrawal.** A shipped code that is
  gone needs its row in `scripts/refusals.withdrawn` (set, code, the tag
  it shipped in, the release it left in, why), and a code with a row is
  not in the catalog: a withdrawn code is not used again. The page
  lists the rows, and a row the last release tag's page lists never
  leaves the list: the tag's page no longer shows the code as shipped,
  so its row is all that keeps the code from coming back. A tag's page
  whose "Withdrawn" table has other columns than the gate reads, or a
  row that names no code, is red: it is not read as withdrawing nothing.
- **A code is its case's name.** A case carries no serde attribute of
  its own (its code is its name in snake case), and no parameter takes a
  name the wire gives the case itself (`code`, `message`, the set's tag;
  for a refusal's case also `at` and `refusal`).
- **A parameter is a value, not a sentence.** No case of any closed set
  is built with a parameter made by `format!`: in its literal, or by a
  `let` binding made by `format!` a few lines before and given by its
  name.
- **Only the wire's reader makes an `Unknown`.** Its fields are private,
  and its literal stands only in `closed::deserialize`.

--write replaces the page and the samples
(`crates/lakelands-api/src/error/case/samples.json`): one value of every
case and place, which the api's test reads back through an error.
`--shipped <page>` compares the catalog with that page instead of the
last release tag's, to show the rule holds.
"""

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ERRORS = ROOT / "crates/lakelands-api/src"
PAGE = ROOT / "docs/refusals.md"
PAGE_PATH = "docs/refusals.md"
SAMPLES = ROOT / "crates/lakelands-api/src/error/case/samples.json"
WITHDRAWN = ROOT / "scripts/refusals.withdrawn"
WITHDRAWN_PATH = "scripts/refusals.withdrawn"
DECODER = "crates/lakelands-api/src/error/outage.rs"
# Every closed set whose cases a site builds with parameters.
SETS = "Case|Place|Situation|Seam|Flaw|Exchange|Remote"

HEAD = """# Refusals

<!-- Generated by scripts/refusals.py from the catalog; do not edit it by hand. -->

What a refusal of `invalid`, `constraint`, `precondition` or `unanswered`
says, as data: a case's `code`, its parameters, and the sentence they
make, which is the case's only sentence. A case is said at places (`at`,
outermost first), each a case of `Place`; the sentence is the places,
joined by `, `, then `: ` and the case's. On the wire a case and a place
are objects: `code`, the parameters by the names below, and `message`.
A host renders a code it knows in its users' language, and one it does
not know by its message. The rules a code keeps are in
`docs/decisions/015-errors-are-a-closed-set-writes-answer-an-outcome.md`.
"""


UNNAMED = []
# Faults of a set's form: reserved names, a case's own attributes, an
# entry the reader cannot read.
SHAPE = []
# Each catalog set's cases, by its name, and the member that names a case.
CASES = {}
TAGS = {}


def snake(name):
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


ENTRY = re.compile(
    r"((?:[ \t]*///[^\n]*\n)*)[ \t]*([A-Z][A-Za-z0-9]*)\s*(\{(?:[^{}]|\{[^{}]*\})*\})?\s*=>\s*\"((?:[^\"\\]|\\.)*)\",",
    re.S,
)


NAMED_ENTRY = re.compile(r"((?:[ \t]*///[^\n]*\n)*)[ \t]*([A-Z]\w*)\s*=\s*\"(\w+)\"\s*=>\s*\"((?:[^\"\\\\]|\\\\.)*)\",")
# A plain-name set's sentences, by its name: what a parameter of it says.
NAMED = {}


# A catalog set's templates, by its name: what a parameter of it says.
SETS_SAID = {}
# A set this small is said by its templates; a larger one as any text.
SMALL = 8


def bare(ty):
    """A parameter's type without `Option`, `Box` and paths, and whether
    it is a list."""
    ty = re.sub(r"^(?:Option|Box)<(.*)>$", r"\1", ty)
    ty = re.sub(r"^(?:Option|Box)<(.*)>$", r"\1", ty)
    listed = re.match(r"^Vec<(.*)>$", ty)
    ty = listed.group(1) if listed else ty
    return ty.split("::")[-1], bool(listed)


def catalog():
    """Every set: (name, its doc, [(code, [params], template, doc)])."""
    sets = []
    for path in sorted(ERRORS.rglob("*.rs")):
        text = path.read_text()
        for m in re.finditer(r"\nnamed!\s*\{", text):
            depth, i = 1, m.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(text[i], 0)
                i += 1
            body = text[m.end() : i - 1]
            head = re.search(r"((?:\s*///[^\n]*\n)*)\s*pub enum (\w+)\s*\{", body)
            doc = " ".join(l.strip()[3:].strip() for l in head.group(1).splitlines() if l.strip())
            cases = []
            for e in NAMED_ENTRY.finditer(body[head.end() :]):
                cdoc = " ".join(l.strip()[3:].strip() for l in e.group(1).splitlines() if l.strip())
                cases.append((e.group(3), [], e.group(4).replace('\\"', '"'), cdoc))
            NAMED[head.group(2)] = [t for _, _, t, _ in cases]
            sets.append((head.group(2), doc, cases))
    for path in sorted(ERRORS.rglob("*.rs")):
        text = path.read_text()
        for m in re.finditer(r"\ncatalog!\s*\{", text):
            depth, i = 1, m.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(text[i], 0)
                i += 1
            body = text[m.end() : i - 1]
            head = re.search(r"((?:\s*///[^\n]*\n)*)\s*pub enum (\w+)\s*\{", body)
            doc = " ".join(l.strip()[3:].strip() for l in head.group(1).splitlines() if l.strip())
            tag = re.search(r'\btag\s*=\s*"(\w+)"\s*;', body[: head.end()])
            set_name = head.group(2)
            TAGS[set_name] = tag.group(1) if tag else "code"
            reserved = {"code", "message", tag.group(1) if tag else "code"}
            if set_name == "Case":
                reserved |= {"at", "refusal"}
            entries = body[head.end() :]
            depth, top, k, start = 0, [], 0, True
            while k < len(entries):
                c = entries[k]
                if c == '"':
                    k = entries.index('"', k + 1) if '"' in entries[k + 1 :] else len(entries)
                    while entries[k - 1] == "\\":
                        k = entries.index('"', k + 1)
                elif c == "\n":
                    start = True
                elif c in " \t":
                    pass
                else:
                    if start and depth == 0 and entries.startswith("#[", k):
                        line = entries[k : entries.find("\n", k)]
                        SHAPE.append(f"{set_name}: a case carries an attribute of its own ({line}); its code is its name")
                    start = False
                    depth += {"{": 1, "}": -1}.get(c, 0)
                    if depth == 0 and entries.startswith("=>", k):
                        top.append(k)
                k += 1
            cases = []
            for e in ENTRY.finditer(entries):
                cdoc = " ".join(l.strip()[3:].strip() for l in e.group(1).splitlines() if l.strip())
                params = []
                fields = r"((?:#\[[^\]]*\]\s*)*)(\w+)\s*:\s*([\w:<>]+(?:<[\w:<>]+>)?)"
                for attrs, name, ty in re.findall(fields, e.group(3) or ""):
                    wire = re.search(r'rename\s*=\s*"([^"]+)"', attrs)
                    params.append((name, wire.group(1) if wire else name, ty))
                    if (wire.group(1) if wire else name) in reserved:
                        SHAPE.append(f"{set_name}::{e.group(2)} has a parameter `{name}`, a name the wire gives the case itself")
                template = e.group(4).replace('\\"', '"').replace("{{", "\0").replace("}}", "\1")
                named = set(re.findall(r"\{\??(\w+)\}", template))
                if named != {name for name, _, _ in params}:
                    UNNAMED.append(f"{head.group(2)}::{e.group(2)} names {sorted(named)} and has {sorted(n for n, _, _ in params)}")
                for name, wire, ty in params:
                    mark = wire + "!t:" + ty + "}"
                    template = template.replace("{" + name + "}", "{" + mark)
                    template = template.replace("{?" + name + "}", "{?" + mark)
                template = template.replace("\0", "{{").replace("\1", "}}")
                cases.append((snake(e.group(2)), [(w, ty) for _, w, ty in params], template, cdoc))
            if len(cases) != len(top):
                SHAPE.append(f"{set_name}: {len(top)} entries, of which {len(cases)} are read; write each as `Name {{ … }} => \"…\",`")
            sets.append((head.group(2), doc, cases))
            SETS_SAID[head.group(2)] = [t for _, _, t, _ in cases]
            CASES[head.group(2)] = cases
    return sets


def shown(ty):
    """A parameter's type as the page says it, and whether it is optional."""
    optional = ty.startswith("Option<")
    kind, listed = bare(ty)
    return (f"list of {kind}" if listed else kind), optional


def param_cell(params):
    out = []
    for wire, ty in params:
        kind, optional = shown(ty)
        out.append(f"`{wire}` ({kind}{', optional' if optional else ''})")
    return ", ".join(out) or "—"


def page(sets):
    out = [HEAD]
    for name, doc, cases in sets:
        out.append(f"\n## `{name}`\n\n{doc}\n\n| code | parameters | sentence | about |\n|---|---|---|---|\n")
        for code, params, template, cdoc in cases:
            sentence = re.sub(r"!t:[^}]*\}", "}", template).replace("|", "\\|")
            out.append(f"| `{code}` | {param_cell(params)} | {sentence} | {cdoc} |\n")
    rows = withdrawn()[0]
    if rows:
        out.append(WITHDRAWN_HEAD)
        for name, code, since, left, why in rows:
            out.append(f"| `{name}::{code}` | {since} | {left} | {why} |\n")
    out.append(VALUES_HEAD)
    for kind, (values, doc) in sorted(value_tables(sets).items()):
        out.append(f"\n### `{kind}`\n\n{doc}\n\n" + ", ".join(f"`{v}`" for v in values) + "\n")
    return "".join(out)


WITHDRAWN_COLUMNS = "| code | shipped in | left in | why |"
WITHDRAWN_HEAD = f"""
## Withdrawn

Codes a release shipped that the product no longer says. No later
release uses one again; a host may still meet one from an older server,
whose own page says its sentence.

{WITHDRAWN_COLUMNS}
|---|---|---|---|
"""

VALUES_HEAD = """
## Parameter types

A parameter of a set above is that set's case; a plain name is said by
its own sentence. The other types:

- **text** (`String`), a **name** (`TypeName`, `FieldName`, `RelationName`,
  `VerbName`, `ParamName`, `TriggerName`, `ValueTypeName`, `LakeId`,
  `SourceId`, `KeyId`) or a **record key** (`RecordKey`): a string;
- a **number** (`u16`, `u32`, `u64`, `usize`, `i32`, `i64`, `Number`) or
  a **position** (`Position`): a JSON number;
- an **instant** (`Timestamp`): an RFC 3339 string in UTC; a
  **proposal's identifier** (`ProposalId`): a string;
- a **field's type** (`FieldType`): an object as a declaration writes
  it, `kind` and what the kind takes; a **bound backend** (`Bound`):
  `model` and `dimensions`;
- **`Names`**: a list of strings, said "`a`, `b`";
- **`Detail`**: an operating system's, a database's or a library's own
  words, scrubbed at their source; never a key, a value or a host path;
- **`Value`**: a JSON value the caller gave;
- **`Error`**: a nested error, as the error's own JSON;
- **`bool`**: a flag, said only by the segment it switches.

These types are said by a name of a closed list:
"""

# Types a parameter has whose values are no table.
SCALARS = {
    "String", "char", "u16", "u32", "u64", "usize", "i64", "bool", "Number", "Value",
    "Position", "TypeName", "FieldName", "RelationName", "VerbName", "RecordKey",
    "ParamName", "TriggerName", "ValueTypeName", "LakeId", "SourceId", "KeyId", "Names",
    "Detail", "Error", "i32", "Timestamp", "ProposalId", "FieldType", "Bound",
}


def enum_values(kind):
    """The wire names of a plain enum of the api crate, and its doc: None
    if it is none."""
    for path in sorted(ERRORS.rglob("*.rs")):
        text = path.read_text()
        m = re.search(r"\n[ \t]*pub enum " + kind + r"\s*\{", text)
        if not m:
            continue
        # Its doc and attributes: the lines above it back to the end of
        # the item before, a derive over several lines included.
        above = []
        for line in reversed(text[: m.start()].split("\n")):
            if not line.strip() or line.rstrip().endswith(("}", ";", "{")) and not line.strip().startswith(("#[", "///")):
                break
            above.insert(0, line)
        head = "\n".join(above)
        depth, i = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body = re.sub(r"[ \t]*///[^\n]*\n", "", text[m.end() : i - 1])
        rename = re.search(r'rename_all\s*=\s*"(\w+)"', head)
        doc = " ".join(l.strip()[3:].strip() for l in head.splitlines() if l.strip().startswith("///"))
        values = []
        for attrs, name, rest in re.findall(r"((?:#\[[^\]]*\]\s*)*)([A-Z]\w*)\s*([,({]|$)", body):
            if rest in "({":
                return None
            own = re.search(r'rename\s*=\s*"([^"]+)"', attrs)
            how = rename.group(1) if rename else ""
            wire = own.group(1) if own else snake(name) if how == "snake_case" else name.lower() if how == "lowercase" else name
            values.append(wire)
        return values, doc
    return None


def value_tables(sets):
    tables = {}
    for _, _, cases in sets:
        for _, params, _, _ in cases:
            for _, ty in params:
                kind, _ = bare(ty)
                if kind in SCALARS or kind in NAMED or kind in SETS_SAID or kind in tables:
                    continue
                found = enum_values(kind)
                if found is None:
                    SHAPE.append(f"the parameter type `{kind}` is neither a set, a scalar nor a plain enum, so the page has no table for it")
                    tables[kind] = ([], "")
                else:
                    tables[kind] = found
    return tables


# What a parameter of a type can say, beyond text without a backtick.
CLASS = {
    "Names": "!n",
    "Detail": "!a",
    "u16": "!d",
    "u32": "!d",
    "u64": "!d",
    "usize": "!d",
    "Position": "!d",
    "Error": "!a",
    "Case": "!a",
    "Place": "!a",
    "Exchange": "!a",
    "Flaw": "!a",
    "Remote": "!a",
    "NameSource": "!a",
    "NameProblem": "!a",
}
ANY, STAR = "any", "star"
CHARS = {
    "b": lambda c: c != "`",
    "a": lambda c: True,
    "d": lambda c: c.isdigit(),
}


def said_as(ty, depth):
    """What a parameter of type `ty` can say: alternatives of tokens."""
    kind, listed = bare(ty)
    if kind in NAMED:
        # What a lake says: a name a reader does not know is never said by
        # the lake that wrote it.
        alts = [list(t) for t in NAMED[kind]]
    elif kind in SETS_SAID and len(SETS_SAID[kind]) <= SMALL and depth < 2:
        alts = [a for t in SETS_SAID[kind] for a in sentences(t, depth + 1)]
    elif kind == "Names":
        return [["`", (ANY, "a"), (STAR, "a"), "`"]]
    else:
        cls = {"!a": "a", "!d": "d"}.get(CLASS.get(kind), "b")
        if kind in SETS_SAID or listed:
            cls = "a"
        return [[(ANY, cls), (STAR, cls)]]
    # A list says one of them first, and then anything.
    return [a + [(STAR, "a")] for a in alts] if listed else alts


def sentences(template, depth=0):
    """Every sentence a template can say, as characters and wildcards: a
    parameter is one character of its class and then any more, a list of
    names is that between backticks, `{?p}` says nothing, and a segment
    `[a|b]` is said as `a` or as `b` (empty when not given)."""
    pos = 0

    def seq():
        nonlocal pos
        out = [[]]
        while pos < len(template):
            two = template[pos : pos + 2]
            if two in ("{{", "}}"):
                out = [o + [two[0]] for o in out]
                pos += 2
                continue
            c = template[pos]
            if c in "|]":
                return out
            if c == "{":
                end = template.index("}", pos)
                g = template[pos : end + 1]
                pos = end + 1
                if g.startswith("{?"):
                    continue
                alts = said_as(g[g.index("!t:") + 3 : -1], depth)
                out = [o + a for o in out for a in alts]
            elif c == "[":
                pos += 1
                alts = seq()
                if template[pos] == "|":
                    pos += 1
                    alts = alts + seq()
                else:
                    alts = alts + [[]]
                pos += 1
                out = [o + a for o in out for a in alts]
            else:
                out = [o + [c] for o in out]
                pos += 1
        return out

    return seq()


def wild(t):
    return isinstance(t, tuple)


def fits(a, b):
    """Whether one character can stand for both tokens."""
    if wild(a) and wild(b):
        return True
    if wild(a) or wild(b):
        (_, cls), c = (a, b) if wild(a) else (b, a)
        return CHARS[cls](c)
    return a == b


def meet(p, q):
    """Whether some text matches both token lists."""
    seen, todo = set(), [(0, 0)]
    while todo:
        i, j = todo.pop()
        if (i, j) in seen:
            continue
        seen.add((i, j))
        if i == len(p) and j == len(q):
            return True
        star = lambda t: wild(t) and t[0] == STAR
        if i < len(p) and star(p[i]):
            todo.append((i + 1, j))
        if j < len(q) and star(q[j]):
            todo.append((i, j + 1))
        if i < len(p) and j < len(q) and fits(p[i], q[j]):
            todo.append((i if star(p[i]) else i + 1, j if star(q[j]) else j + 1))
    return False


def injective(sets):
    faults = []
    for name, _, cases in sets:
        toks = [(code, v) for code, _, t, _ in cases for v in sentences(t)]
        found = set()
        for x in range(len(toks)):
            if all(wild(t) for t in toks[x][1]) and toks[x][0] not in found:
                found.add(toks[x][0])
                faults.append(f"{name}::{toks[x][0]} is only parameters, so it can say anything")
            for y in range(x + 1, len(toks)):
                pair = (toks[x][0], toks[y][0])
                if pair[0] != pair[1] and pair not in found and meet(toks[x][1], toks[y][1]):
                    found.add(pair)
                    faults.append(f"{name}: `{pair[0]}` and `{pair[1]}` can say the same sentence")
    return faults


def released(sets):
    """The page at the last release tag, as `shipped` reads it."""
    tag = subprocess.run(
        ["git", "describe", "--tags", "--abbrev=0", "--match", "v*", "HEAD"],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout.strip()
    if not tag:
        return tag, ({}, set(), [])
    old = subprocess.run(["git", "show", f"{tag}:{PAGE_PATH}"], cwd=ROOT, capture_output=True, text=True)
    if old.returncode != 0:
        return tag, ({}, set(), [])
    return tag, shipped(old.stdout)


def shipped(text):
    """A page's codes and parameters, as {set: {code: params}}, the
    codes its "Withdrawn" table names, as {(set, code)}, and what of
    that table cannot be read: a table under other columns, or a row
    that names no code, would otherwise be a page that withdrew nothing."""
    out, current, gone, unread, table = {}, None, set(), [], None
    for line in text.splitlines():
        m = re.match(r"## `(\w+)`", line)
        if m:
            current = out.setdefault(m.group(1), {})
        elif line.startswith("## "):
            current, table = None, [] if line == "## Withdrawn" else None
        m = re.match(r"\| `(\w+)` \| ([^|]*) \|", line)
        if m and current is not None:
            cell = re.findall(r"`(\w+)` \(([^),]*)(, optional)?\)", m.group(2))
            current[m.group(1)] = {n: (k, bool(o)) for n, k, o in cell}
        m = re.match(r"\| `(\w+)::(\w+)` \|", line)
        if m:
            gone.add(m.groups())
        if table is not None and line.startswith("|"):
            table.append(line)
            if table[0] != WITHDRAWN_COLUMNS:
                if len(table) == 1:
                    unread.append(f'"Withdrawn" table is headed `{line}`, not `{WITHDRAWN_COLUMNS}`')
            elif len(table) > 2 and not m:
                unread.append(f'"Withdrawn" table has a row that names no `Set::code`: `{line}`')
    return out, gone, unread


def withdrawn():
    """The rows of the withdrawn list, as (set, code, shipped in, left in, why), and its faults."""
    rows, faults = [], []
    if not WITHDRAWN.exists():
        return rows, faults
    for n, line in enumerate(WITHDRAWN.read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        cells = tuple(c.strip() for c in line.split("|"))
        if len(cells) != 5 or not all(cells):
            faults.append(f"{WITHDRAWN_PATH}:{n} is not `set | code | shipped in | left in | why`")
        elif cells[:2] in [r[:2] for r in rows]:
            faults.append(f"{WITHDRAWN_PATH}:{n} names {cells[0]}::{cells[1]} a second time")
        else:
            rows.append(cells)
    return rows, faults


def stable(sets, old_page=None):
    tag, (old, gone, unread) = released(sets) if old_page is None else ("the given page", old_page)
    rows, faults = withdrawn()
    left = {r[:2] for r in rows}
    # A table the gate cannot read is not a page that withdrew nothing.
    faults += [f"{tag}: its {fault}; a withdrawal it lists would be forgotten" for fault in unread]
    # A withdrawal a release shipped stays: without its row the code
    # could come back with another meaning once no page lists it as live.
    for name, code in sorted(gone - left):
        faults.append(f"{name}::{code} is withdrawn in {tag} and has no row in {WITHDRAWN_PATH}: a row never leaves")
    now = {
        name: {code: {w: shown(ty) for w, ty in params} for code, params, _, _ in cases}
        for name, _, cases in sets
    }
    for name, code in sorted(left):
        if code in now.get(name, {}):
            faults.append(f"{name}::{code} is in the catalog and has a row in {WITHDRAWN_PATH}: a code in use has no row, and a withdrawn code is not used again")
    for name, codes in old.items():
        for code, params in codes.items():
            if code not in now.get(name, {}):
                if (name, code) not in left:
                    faults.append(f"{name}::{code} shipped in {tag} and is gone or renamed; a code leaves only by its row in {WITHDRAWN_PATH}")
                continue
            have = now[name][code]
            for p, was in params.items():
                if p not in have:
                    faults.append(f"{name}::{code} lost `{p}`, which {tag} shipped")
                elif have[p] != was:
                    faults.append(f"{name}::{code}: `{p}` was {was[0]}{' (optional)' * was[1]} in {tag}, and is {have[p][0]}{' (optional)' * have[p][1]}")
            for p, (kind, optional) in have.items():
                if p not in params and not optional:
                    faults.append(f"{name}::{code} gains `{p}`, which is not optional; a shipped case gains optional parameters only")
    return faults


# A value of each scalar type, as the wire writes it.
SAMPLE = {
    "String": "s", "char": "c", "u16": 1, "u32": 1, "u64": 1, "usize": 1, "i32": 1, "i64": 1,
    "bool": True, "Number": 1, "Value": 1, "Position": 1, "TypeName": "t", "FieldName": "f",
    "RelationName": "r", "VerbName": "v", "RecordKey": "k", "ParamName": "p",
    "TriggerName": "g", "ValueTypeName": "vt", "LakeId": "lake", "SourceId": "src", "KeyId": "1",
    "Names": ["a"], "Detail": "d", "Error": {"error": "refused", "reason": {"refusal": "not_granted"}},
    "Timestamp": "2026-01-01T00:00:00Z", "ProposalId": "p-1", "FieldType": {"kind": "text"},
    "Bound": {"model": "m", "dimensions": 2},
}


def sample_of(ty, sets, depth=0):
    """A value of a parameter's type, as the wire writes it."""
    kind, listed = bare(ty)
    if kind in SAMPLE:
        one = SAMPLE[kind]
    elif kind in NAMED:
        one = next(c for n, _, cases in sets if n == kind for c, _, _, _ in cases[:1])
    elif kind in CASES:
        one = sample_case(kind, CASES[kind][0], sets, depth + 1)
    else:
        tables = value_tables(sets)
        one = tables[kind][0][0] if tables.get(kind, ([],))[0] else None
    return [one] if listed else one


def sample_case(set_name, case, sets, depth=0):
    code, params, _, _ = case
    out = {TAGS.get(set_name, "code"): code}
    for wire, ty in params:
        out[wire] = sample_of(ty, sets, depth)
    return out


def samples(sets):
    """One value of every case and every place, as the wire writes it."""
    import json
    out = {name: [sample_case(name, c, sets) for c in CASES[name]] for name in ("Case", "Place")}
    return json.dumps(out, indent=1, sort_keys=True) + "\n"


def tracked_sources():
    files = subprocess.run(
        ["git", "ls-files", "crates/*/src/**.rs"], cwd=ROOT, capture_output=True, text=True
    ).stdout.split()
    return [f for f in files if (ROOT / f).exists()]


LITERAL = re.compile(r"\b(?:" + SETS + r")::[A-Z]\w*\s*\{")


def built_by_format():
    faults = []
    for f in tracked_sources():
        text = (ROOT / f).read_text()
        made = {}
        for m in re.finditer(r"let\s+(\(?[\w\s,]+\)?)\s*=\s*\(?\s*format!", text):
            first = m.group(1).strip("() ").split(",")[0].strip()
            made.setdefault(first, []).append(m.start())
        for m in LITERAL.finditer(text):
            depth, i = 1, m.end()
            while depth and i < len(text):
                depth += {"{": 1, "}": -1}.get(text[i], 0)
                i += 1
            body = text[m.end() : i - 1]
            line = text.count("\n", 0, m.start()) + 1
            if "format!" in body:
                faults.append(f"{f}:{line}: a case is built with a `format!` parameter")
            for name in re.findall(r"(?:^|[{,\s])(\w+)\s*(?=,|$)", body.strip()):
                if any(0 < m.start() - at < 1500 for at in made.get(name, [])):
                    faults.append(f"{f}:{line}: `{name}` is made by `format!` and given to a case")
    return faults


def unknown_made():
    faults = []
    for f in tracked_sources():
        text = (ROOT / f).read_text()
        for m in re.finditer(r"\bUnknown\s*\{\s*code\b", text):
            line = text.count("\n", 0, m.start()) + 1
            if f != DECODER:
                faults.append(f"{f}:{line}: an `Unknown` is made outside the wire's reader")
    return faults


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    sets = catalog()
    text = page(sets)
    total = sum(len(c) for _, _, c in sets)
    if mode == "--write":
        PAGE.write_text(text)
        SAMPLES.write_text(samples(sets))
        print(f"refusals: wrote {PAGE_PATH}: {total} cases in {len(sets)} sets")
        return 0
    faults = []
    if not PAGE.exists() or PAGE.read_text() != text:
        faults.append(f"{PAGE_PATH} is not what the catalog says; run scripts/refusals.py --write")
    if not SAMPLES.exists() or SAMPLES.read_text() != samples(sets):
        faults.append("the samples are not what the catalog says; run scripts/refusals.py --write")
    against = None
    if "--shipped" in sys.argv:
        against = shipped(Path(sys.argv[sys.argv.index("--shipped") + 1]).read_text())
    faults += UNNAMED + SHAPE + injective(sets) + stable(sets, against) + built_by_format() + unknown_made()
    for f in faults:
        print(f"refusals: {f}", file=sys.stderr)
    if faults:
        print(f"refusals: RED ({len(faults)} violation(s))", file=sys.stderr)
        return 1
    print(f"refusals: green ({total} cases in {len(sets)} sets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
